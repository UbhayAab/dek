// The two generated documents. Counts, ids and hashes only: no names, emails,
// bodies, file names, endpoints or tokens.
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ORGS, DOCS_DIR } from './config.mjs';
import { RULES } from './decisions.mjs';

const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`,
  ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const mb = (n) => `${(n / 1048576).toFixed(1)} MB`;

export function orgCounts(plan) {
  const R = plan.rows;
  return ORGS.map((o) => {
    const ch = R.channels.filter((c) => c.org_id === o.id);
    const chIds = new Set(ch.map((c) => c.id));
    const msgs = R.messages.filter((m) => m.org_id === o.id);
    const dmIds = new Set(ch.filter((c) => !c.server_id).map((c) => c.id));
    const atts = R.attachments.filter((a) => a.org_id === o.id);
    const members = new Set(R.org_members.filter((m) => m.org_id === o.id).map((m) => m.user_id));
    return {
      org: o,
      members: members.size,
      owners: R.org_members.filter((m) => m.org_id === o.id && m.role === 'owner').length,
      admins: R.org_members.filter((m) => m.org_id === o.id && m.role === 'admin').length,
      servers: R.servers.filter((s) => s.org_id === o.id).length,
      servers_archived: R.servers.filter((s) => s.org_id === o.id && s.archived_at).length,
      server_members: R.server_members.filter((m) => m.org_id === o.id).length,
      text: ch.filter((c) => c.kind === 'text').length,
      audio: ch.filter((c) => c.kind === 'audio').length,
      private: ch.filter((c) => c.server_id && c.visibility === 'private').length,
      dms: dmIds.size,
      channel_members: R.channel_members.filter((m) => chIds.has(m.channel_id)).length,
      messages_channel: msgs.filter((m) => !dmIds.has(m.channel_id)).length,
      messages_dm: msgs.filter((m) => dmIds.has(m.channel_id)).length,
      deleted: msgs.filter((m) => m.deleted_at).length,
      roots: new Set(msgs.filter((m) => m.thread_root_id).map((m) => m.thread_root_id)).size,
      replies: msgs.filter((m) => m.thread_root_id).length,
      reactions: R.reactions.filter((r) => r.org_id === o.id).length,
      mentions: R.mentions.filter((r) => r.org_id === o.id).length,
      attachments: atts.length,
      bytes: atts.reduce((a, x) => a + x.size_bytes, 0),
      pins: msgs.filter((m) => m.pinned_at).length,
      saved: R.saved_messages.filter((s) => s.org_id === o.id).length,
      cursors: R.channel_members.filter((m) => chIds.has(m.channel_id) && m.last_read_seq > 0).length,
      thread_follows: R.thread_follows.filter((t) => t.org_id === o.id).length,
      invites: R.invites.filter((i) => i.org_id === o.id).length,
      join_requests: R.join_requests.filter((j) => j.org_id === o.id).length,
      devices: R.push_devices.filter((d) => members.has(d.user_id)).length,
    };
  });
}

const COUNT_ROWS = [['members', 'org members'], ['owners', 'owners'], ['admins', 'admins'],
  ['servers', 'servers'], ['servers_archived', 'servers archived'], ['server_members', 'server members'],
  ['text', 'text channels'], ['audio', 'audio channels'], ['private', 'private server channels'],
  ['dms', 'DM channels'], ['channel_members', 'channel memberships'], ['messages_channel', 'channel messages'],
  ['messages_dm', 'DM messages'], ['deleted', 'deleted (tombstones)'], ['roots', 'thread roots with replies'],
  ['replies', 'thread replies'], ['reactions', 'reactions'], ['mentions', 'mention rows'],
  ['attachments', 'attachments'], ['bytes', 'attachment bytes'], ['pins', 'pins'], ['saved', 'saved'],
  ['cursors', 'read cursors > 0'], ['thread_follows', 'thread follow rows'], ['invites', 'invites'],
  ['join_requests', 'join requests'], ['devices', 'push devices of members']];

export function writePlanDoc(plan, d, target) {
  const s = plan.stats;
  const per = orgCounts(plan);
  const lines = [
    '# Legacy migration plan run',
    '',
    `Generated by \`node tools/migrate-legacy/index.mjs --plan\` at ${new Date().toISOString()}.`,
    `Legacy snapshot: ${d.snapshot.at} (one REPEATABLE READ READ ONLY transaction, project ybddogqphinruyunnuwx).`,
    'Nothing was written to the new project except the run log in `dek_migration.runs`.',
    'Counts, ids and hashes only. Rules: section 2. Evidence for the rules: `docs/migration/LEGACY-MAP.md`.',
    '',
    '## 1. Counts per organization (after the mapping rules)',
    '',
    table(['', ...per.map((p) => `${p.org.name} \`${p.org.id}\``)],
      COUNT_ROWS.map(([k, label]) => [label, ...per.map((p) => (k === 'bytes' ? mb(p[k]) : String(p[k])))])),
    '',
    '## 2. Decisions',
    '',
    ...RULES.map(([area, text], i) => `${i + 1}. **${area}.** ${text}`),
    '',
    '### Resolved from this snapshot',
    '',
    ...plan.decisions.map((x) => `- ${x.area}: ${x.text}`),
    `- invite hashing: legacy database encoding ${d.snapshot.encoding}; extensions.digest(text, 'sha256') = sha256(convert_to(text, 'UTF8')) is ${d.snapshot.digest_is_sha256_utf8}.`,
    `- channel_overwrites in the real orgs: ${d.channelOverwrites} (no per-channel view denials to carry).`,
    '',
    '## 3. Users and sessions',
    '',
    table(['measure', 'count'], Object.entries(s.users).map(([k, v]) => [k, typeof v === 'object' ? JSON.stringify(v) : String(v)])),
    '',
    table(['measure', 'count'], [
      ...Object.entries(s.profiles).map(([k, v]) => [`profiles.${k}`, String(v)]),
      ...Object.entries(s.notification_prefs).map(([k, v]) => [`notification_prefs.${k}`, String(v)]),
      ...Object.entries(s.platform_admins).map(([k, v]) => [`platform_admins.${k}`, String(v)]),
    ]),
    '',
    '## 4. Roles, spaces, messages',
    '',
    `- server roles: ${JSON.stringify(s.server_roles)}`,
    `- legacy channel kinds: ${JSON.stringify(s.channel_kinds)}`,
    `- DMs: ${JSON.stringify(s.dms)}`,
    `- messages: ${JSON.stringify(s.messages)}`,
    `- read state: ${JSON.stringify(s.read_state)}`,
    `- thread follows: ${JSON.stringify(s.thread_follows)}`,
    `- saved: ${JSON.stringify(s.saved)}`,
    `- invites: ${JSON.stringify(s.invites)}`,
    `- push devices: ${JSON.stringify(s.push_devices)}`,
    `- files: ${plan.objects.length} objects to copy (${plan.objects.filter((o) => o.kind === 'attachment').length} attachments, ${plan.objects.filter((o) => o.kind === 'thumb').length} thumbnails, ${plan.objects.filter((o) => o.kind === 'avatar').length} avatars), ${mb(plan.objects.reduce((a, o) => a + o.size, 0))}`,
    `- id map entries: ${plan.idMap.length}`,
    `- archive (not loaded): ${JSON.stringify(Object.fromEntries(Object.entries(d.archive).map(([k, v]) => [k, v.length])))}`,
    '',
    '## 5. Warnings',
    '',
    ...(plan.warnings.length ? plan.warnings.map((w) => `- ${w}`) : ['- none']),
    '',
    '## 6. Delta against the new project now (read only)',
    '',
    'What `--apply` would do with this snapshot, by registry key (dek_migration.owned). Rows whose key is present can still be updated in place (a new reaction summary, a moved cursor); `--apply --dry-run` prints the exact inserted, updated and deleted counts.',
    '',
    target ? table(['kind', 'written by earlier runs', 'planned now', 'to add', 'to remove'],
      target.map((t) => [t.name, String(t.present), String(t.planned), String(t.add), String(t.remove)]))
      : 'Not read.',
    '',
  ];
  mkdirSync(DOCS_DIR, { recursive: true });
  writeFileSync(join(DOCS_DIR, 'PLAN-RUN.md'), `${lines.join('\n')}\n`);
}

export function writeReconciliationDoc(r) {
  const status = (x) => (x ? 'match' : '**DIFFERENT**');
  const lines = [
    '# Legacy migration reconciliation (DEKA16)',
    '',
    `Generated by \`node tools/migrate-legacy/index.mjs --verify\` at ${new Date().toISOString()}.`,
    `Legacy snapshot: ${r.snapshot}. Counts are read independently from both databases; expected values apply the mapping rules of PLAN-RUN.md section 2 to legacy data.`,
    '',
    `**Result: ${r.ok ? 'RECONCILED' : 'NOT RECONCILED'}** (${r.checks.filter((c) => c.ok).length} of ${r.checks.length} checks match).`,
    '',
    '## 1. Counts',
    '',
    table(['org', 'check', 'legacy (raw)', 'expected', 'new', 'result', 'note'],
      r.checks.map((c) => [c.org, c.name, String(c.legacy ?? ''), String(c.expected), String(c.actual),
        c.ok ? 'match' : (c.info ? 'moved (live data)' : '**DIFFERENT**'), c.note || ''])),
    '',
    '## 2. Message samples',
    '',
    `${r.samples.length} random messages (seed ${r.seed}): author, channel, created_at and the sha256 of the normalised text (mention syntax, quote line and card wrapper removed) compared. The digests are compared in memory and not printed: a short message is guessable from an unsalted hash.`,
    '',
    table(['message', 'author', 'channel', 'created_at', 'text', 'result'],
      r.samples.map((x) => [x.id, status(x.author), status(x.channel), status(x.created), status(x.text), x.ok ? 'match' : '**DIFFERENT**'])),
    '',
    '## 3. Permissions',
    '',
    `${r.users.length} random users (seed ${r.seed}): the set of readable channels and DMs in legacy (workspace member and public, or channel member; conversation member) against dek.can_read_channel in the new project.`,
    '',
    table(['user', 'legacy readable', 'new readable', 'missing in new', 'extra in new', 'result'],
      r.users.map((u) => [u.id, String(u.legacy), String(u.actual), String(u.missing), String(u.extra), status(u.ok)])),
    '',
    r.allUsers ? `All ${r.allUsers.members} migrated users checked the same way: ${r.allUsers.ok} identical sets (${r.allUsers.pairs} readable channel and DM pairs in legacy; ${r.allUsers.with_nothing} people read nothing in either, being in no server and no DM).` : '',
    ...(r.allUsers?.explained?.length ? ['', `Intended difference (${r.allUsers.explained.length} pairs): a DM of an org the person no longer belongs to. Legacy let conversation members read it after leaving; the new access rule (dek.can_read_channel) requires an active membership of the DM's org, as for every other channel. The other person keeps the conversation. Pairs: ${r.allUsers.explained.join('; ')}.`] : []),
    '',
    '## 4. Files',
    '',
    `Every copied object downloaded again from the new project: ${r.files.ok} of ${r.files.objects} match the recorded legacy sha256 and size (${(r.files.bytes / 1048576).toFixed(1)} MB). Legacy attachment rows with a stored sha256 checked: ${r.files.legacy_row_sha_checked}, mismatches ${r.files.legacy_row_sha_mismatch.length}.`,
    ...(r.files.mismatched.length ? [`Mismatched: ${r.files.mismatched.join(', ')}`] : []),
    '',
    '## 5. Invariants in the new project',
    '',
    ...r.invariants.map((x) => `- ${x.ok ? 'ok' : '**FAILED**'}: ${x.name}${x.detail ? ` (${x.detail})` : ''}`),
    '',
    '## 6. Explained differences',
    '',
    ...(r.explained.length ? r.explained.map((x) => `- ${x}`) : ['- none']),
    '',
  ];
  mkdirSync(DOCS_DIR, { recursive: true });
  writeFileSync(join(DOCS_DIR, 'RECONCILIATION.md'), `${lines.join('\n')}\n`);
}
